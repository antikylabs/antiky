#!/usr/bin/env node
/**
 * Build the hue-shifting lighting ramp for `traversal-study`.
 *
 * The demo's lighting was three `smoothstep` bands spanning 0.54 to 0.98 — a 1.81:1 range with no
 * hue movement at all, which is a complete explanation for why a platformer whose whole subject is
 * material read as flat. Light and shadow differed only in how much grey they had.
 *
 * A ramp fixes that by deciding what a surface looks like at each light level rather than scaling it.
 * Shadows go cool and deep, midtones carry the most chroma, highlights go warm and pale — the same
 * move a painter makes, and the reason stylised games read as lit rather than as tinted.
 *
 * Emitted as a TypeScript constant rather than an image because BroMetal's only raw-buffer texture
 * upload is `createTexture3D` (`runtime/texture.d.ts:37`) — there is no way to hand it a byte array
 * for a 2D texture. A committed constant is also diffable and testable as data, which is what AC-L1
 * measures.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const STEPS = 64;
/**
 * Control points from shadow to highlight, in linear light.
 *
 * Deliberately not a two-colour gradient: the midtone is where chroma lives, and interpolating
 * straight from a blue shadow to a cream highlight passes through grey exactly where the eye is
 * most sensitive to it.
 */
const CONTROL = [
  // The shadow end was [0.045, 0.062, 0.140] — near black and strongly blue, which made every
  // surface facing away from the sun read as a dark hole and dragged the whole demo down. A
  // platformer sky this bright bounces a lot of light into its own shadows; they should be *cooler*
  // than the lit side, not absent from it.
  [0.0, [0.120, 0.140, 0.230]],
  [0.35, [0.330, 0.320, 0.390]],
  [0.60, [0.600, 0.500, 0.440]],
  [0.82, [0.890, 0.790, 0.590]],
  [1.0, [1.000, 0.950, 0.820]],
];

function sample(at) {
  for (let index = 0; index < CONTROL.length - 1; index += 1) {
    const [leftAt, left] = CONTROL[index];
    const [rightAt, right] = CONTROL[index + 1];
    if (at > rightAt) continue;
    const span = rightAt - leftAt;
    const raw = span === 0 ? 0 : (at - leftAt) / span;
    // Smoothstep between control points so the bands do not show as ridges.
    const t = raw * raw * (3 - 2 * raw);
    return left.map((value, channel) => value + (right[channel] - value) * t);
  }
  return CONTROL[CONTROL.length - 1][1];
}

const rows = [];
for (let step = 0; step < STEPS; step += 1) {
  const colour = sample(step / (STEPS - 1));
  rows.push(`  [${colour.map((value) => Number(value.toFixed(5))).join(', ')}],`);
}

const destination = path.join(
  fileURLToPath(new URL('..', import.meta.url)),
  'antiky/traversal-study/src/lighting-ramp.gen.ts',
);
await writeFile(destination, `/**
 * The lighting ramp, ${STEPS} steps from full shadow to full light, in linear RGB.
 *
 * Generated by \`packages/demos/scripts/build-lighting-ramp.mjs\`. Do not hand-edit: change the
 * control points there and re-run, so the shape stays something a person can reason about rather
 * than sixty-four numbers nobody dares touch.
 */
export const TRAVERSAL_LIGHTING_RAMP = Object.freeze([
${rows.join('\n')}
] as const);
`);
process.stdout.write(`lighting-ramp.gen.ts — ${STEPS} steps\n`);
