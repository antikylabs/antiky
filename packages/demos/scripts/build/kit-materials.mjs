#!/usr/bin/env node
/**
 * Derive a material table for a Kenney palette kit from its own atlas.
 *
 * What the atlas is: a grid of flat colour swatches, sixteen columns by four rows. A mesh's
 * `TEXCOORD_0` picks one — V selects the row, U selects the swatch within it. **The identity is two
 * dimensional**, which is why goal 05's framing of "route material IDs into the UV-V channel" does
 * not fit: V alone names a row of a dozen unrelated colours.
 *
 * What the atlas is not: a material. Nothing in it says a swatch is metal or cloth — the rows are
 * organised by colour family. So the roughness below is **authored on top of measured colour**, by
 * the rule stated in `roughnessFor`, rather than read out of the art. That distinction matters: it
 * means a person can disagree with the rule and change one function, instead of hunting through a
 * table of numbers with no stated origin.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';
import { parseGlb } from 'brometal';

const COLUMNS = 16;
const ROWS = 4;
const demosRoot = fileURLToPath(new URL('../..', import.meta.url));

/**
 * Roughness from colour, by a stated convention rather than a measurement.
 *
 * A saturated bright reads as painted or moulded — plastic, enamel, a coloured panel — and takes
 * light with a tighter highlight. A desaturated or dark swatch reads as stone, bark, dirt or worn
 * metal and scatters. That is the whole rule, and it is a convention about how these kits are used
 * rather than a fact about the pixels.
 *
 * Disagree with it here, in one place, rather than by editing generated numbers.
 */
function roughnessFor([red, green, blue]) {
  const high = Math.max(red, green, blue) / 255;
  const low = Math.min(red, green, blue) / 255;
  const saturation = high === 0 ? 0 : (high - low) / high;
  // 0.42 for a vivid swatch through to 0.95 for a flat grey.
  return Number((0.95 - saturation * 0.53).toFixed(3));
}

async function main() {
  const [, , kitPath, demo, name] = process.argv;
  if (kitPath === undefined) throw new Error('usage: build-kit-materials.mjs <kit-dir> <demo> <NAME>');
  const kitDirectory = path.join(demosRoot, 'antiky', demo, kitPath);
  const files = (await readFile(path.join(kitDirectory, '.'), 'utf8').catch(() => null)) ?? null;
  void files;
  const { readdir } = await import('node:fs/promises');
  const glbs = (await readdir(kitDirectory)).filter((entry) => entry.endsWith('.glb'));
  if (glbs.length === 0) throw new Error(`No GLBs under ${kitDirectory}.`);

  const first = await readFile(path.join(kitDirectory, glbs[0]));
  const model = parseGlb(first.buffer.slice(first.byteOffset, first.byteOffset + first.byteLength));
  const image = model.images[0];
  if (image === undefined) throw new Error('The kit GLB carries no embedded atlas.');
  const { data, info } = await sharp(Buffer.from(image.data)).raw().toBuffer({ resolveWithObject: true });

  const swatches = [];
  for (let row = 0; row < ROWS; row += 1) {
    for (let column = 0; column < COLUMNS; column += 1) {
      const x = Math.round((column + 0.5) * info.width / COLUMNS);
      const y = Math.round((row + 0.5) * info.height / ROWS);
      const at = (y * info.width + x) * info.channels;
      const colour = [data[at], data[at + 1], data[at + 2]];
      // Row 0 of this atlas is empty. An all-black swatch carries no material and is recorded as
      // unused rather than silently given a roughness.
      const unused = colour[0] === 0 && colour[1] === 0 && colour[2] === 0;
      swatches.push({
        row,
        column,
        colour,
        roughness: unused ? null : roughnessFor(colour),
      });
    }
  }

  const rows = swatches.map((swatch) => `  { row: ${swatch.row}, column: ${swatch.column}, `
    + `colour: [${swatch.colour.join(', ')}], roughness: ${swatch.roughness} },`).join('\n');

  await writeFile(path.join(demosRoot, 'antiky', demo, 'src', 'kit-materials.gen.ts'), `/**
 * Material properties for every swatch of this kit's palette atlas.
 *
 * Generated by \`packages/demos/scripts/build-kit-materials.mjs\`, which samples the atlas embedded in
 * the kit's own GLBs. Do not hand-edit — change the rule in that script and re-run.
 *
 * A mesh selects a swatch with both UV components: \`row = floor(v * ${ROWS})\`,
 * \`column = floor(u * ${COLUMNS})\`. \`roughness\` is \`null\` where the atlas is empty.
 *
 * The colours are measured. The roughness is a convention applied to them, documented in the
 * generator — the atlas carries colour identity, not material identity.
 */
export const ${name}_KIT_MATERIALS = Object.freeze([
${rows}
] as const);

export const ${name}_KIT_GRID = Object.freeze({ rows: ${ROWS}, columns: ${COLUMNS} });
`);
  const used = swatches.filter((swatch) => swatch.roughness !== null).length;
  process.stdout.write(`kit-materials.gen.ts — ${swatches.length} swatches, ${used} in use\n`);
}

await main();
